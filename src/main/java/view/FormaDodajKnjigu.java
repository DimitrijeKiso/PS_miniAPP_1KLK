    private void jButtonDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajActionPerformed
            String naslov = jTextFieldNaziv.getText();
            String ISBN = jTextFieldISBN.getText();
              int godinaIzdanja;
            try{
               godinaIzdanja = Integer.parseInt(jTextFieldGodinaIzdanja.getText()); 
            }
          catch (NumberFormatException e){
              JOptionPane.showMessageDialog(this, "Morate da upisete broj", "Upozorenje", JOptionPane.WARNING_MESSAGE);
              return;
          }
            
            Zanr zanr = (Zanr) jComboBoxZanr.getSelectedItem();
            Autor autor = (Autor) jComboBoxAutori.getSelectedItem();
            
            Knjiga k = new Knjiga(autor, naslov, ISBN, godinaIzdanja, zanr);
            
            Controller.getInstance().dodajNovuKnjigu(k);
            JOptionPane.showMessageDialog(this, "Uspesno ste dodali knjigu", "Uspesno!", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
            
            gf.osveziTabelu(); 
            
            
    }//GEN-LAST:event_jButtonDodajActionPerformed

    private void jButtonIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIzmeniActionPerformed
        
        String naslov = jTextFieldNaziv.getText();
            String ISBN = jTextFieldISBN.getText();
              int godinaIzdanja;
            try{
               godinaIzdanja = Integer.parseInt(jTextFieldGodinaIzdanja.getText()); 
            }
          catch (NumberFormatException e){
              JOptionPane.showMessageDialog(this, "Morate da upisete broj", "Upozorenje", JOptionPane.WARNING_MESSAGE);
              return;
          }
            
            Zanr zanr = (Zanr) jComboBoxZanr.getSelectedItem();
            Autor autor = (Autor) jComboBoxAutori.getSelectedItem();
        
            knjigaZaIzmenu.setAutor(autor);
            knjigaZaIzmenu.setGodinaIzdanja(godinaIzdanja);
            knjigaZaIzmenu.setISBN(ISBN);
            knjigaZaIzmenu.setZanr(zanr);
            knjigaZaIzmenu.setNaslov(naslov); 
            
            JOptionPane.showMessageDialog(this, "Uspesno ste izmenili knjigu", "Uspeh", JOptionPane.INFORMATION_MESSAGE);
            
            this.dispose();
            
            gf.osveziTabelu();
        
    }//GEN-LAST:event_jButtonIzmeniActionPerformed

